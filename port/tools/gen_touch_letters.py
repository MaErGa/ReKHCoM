"""The touch buttons' letters (A, B, L, R, SELECT, START) in the HD text's font (port/assets/fonts/KHMenu.otf), drawn
large and kept as 8-bit coverage in port/android/native/touch_letters.inc; touch_android.c scales them down smoothly to
the button's size (no font engine needed on Android, the web or the consoles).

    python port/tools/gen_touch_letters.py
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[2]
WORDS = ['A', 'B', 'L', 'R', 'SELECT', 'START']
font = ImageFont.truetype(str(ROOT / 'port/assets/fonts/KHMenu.otf'), 96)
out = ['/* Generated by port/tools/gen_touch_letters.py from KHMenu.otf: coverage 0..255, cropped to the ink. */',
       'typedef struct TouchLetters { const char* text; int w, h; const unsigned char* a; } TouchLetters;']
table = []
for i, word in enumerate(WORDS):
    im = Image.new('L', (96 * len(word) + 64, 160), 0)
    ImageDraw.Draw(im).text((32, 16), word, fill=255, font=font)
    box = im.getbbox()
    im = im.crop(box)
    data = im.tobytes()
    rows = [','.join(str(b) for b in data[k:k + 40]) for k in range(0, len(data), 40)]
    out.append(f'static const unsigned char kTouchLetters{i}[] = {{\n' + ',\n'.join(rows) + '\n};')
    table.append(f'    {{ "{word}", {im.width}, {im.height}, kTouchLetters{i} }},')
out.append('static const TouchLetters kTouchLetters[] = {\n' + '\n'.join(table) + '\n};')
(ROOT / 'port/android/native/touch_letters.inc').write_text('\n'.join(out) + '\n', encoding='utf-8')
print('ok', [(w) for w in WORDS])
