"""The launcher's emblem beside the RetroAchievements account (our own drawing, not RetroAchievements' logo):
a gold trophy on a dark round badge, 128x128. Writes port/assets/achievements/ra_emblem.png and its embedded copy
port/include/port/ra_emblem_png.inc (as gen_badges_inc.py does for the badges).

    python port/tools/gen_ra_emblem.py
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFilter

ROOT = Path(__file__).resolve().parents[2]
PNG = ROOT / 'port/assets/achievements/ra_emblem.png'
INC = ROOT / 'port/include/port/ra_emblem_png.inc'
S = 4  # supersampling


def emblem():
    W = 128 * S
    im = Image.new('RGBA', (W, W), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    # the badge: a dark disc with a gold ring
    d.ellipse((4 * S, 4 * S, W - 4 * S, W - 4 * S), fill=(24, 22, 40, 255))
    d.ellipse((4 * S, 4 * S, W - 4 * S, W - 4 * S), outline=(214, 170, 60, 255), width=5 * S)
    d.ellipse((12 * S, 12 * S, W - 12 * S, W - 12 * S), outline=(120, 90, 30, 255), width=2 * S)
    gold, light, dark = (238, 192, 70, 255), (255, 236, 150, 255), (150, 105, 25, 255)
    c = W // 2
    # the cup, its handles, the stem and the base
    d.pieslice((c - 30 * S, 22 * S, c + 30 * S, 82 * S), 0, 180, fill=gold)
    d.rectangle((c - 30 * S, 30 * S, c + 30 * S, 52 * S), fill=gold)
    for sx in (-1, 1):
        x = c + sx * 30 * S
        d.arc((x - 14 * S if sx < 0 else x - 4 * S, 34 * S, x + 4 * S if sx < 0 else x + 14 * S, 58 * S),
              90 if sx < 0 else 270, 270 if sx < 0 else 90, fill=gold, width=5 * S)
    d.rectangle((c - 6 * S, 80 * S, c + 6 * S, 92 * S), fill=dark)
    d.rectangle((c - 20 * S, 92 * S, c + 20 * S, 102 * S), fill=gold)
    d.rectangle((c - 24 * S, 100 * S, c + 24 * S, 106 * S), fill=dark)
    # shine and a star on the cup
    d.ellipse((c - 22 * S, 34 * S, c - 12 * S, 60 * S), fill=light)
    star = []
    import math
    for k in range(10):
        r = (11 if k % 2 == 0 else 5) * S
        a = -math.pi / 2 + k * math.pi / 5
        star.append((c + 4 * S + r * math.cos(a), 50 * S + r * math.sin(a)))
    d.polygon(star, fill=(255, 250, 220, 255))
    return im.resize((128, 128), Image.LANCZOS)


def main():
    emblem().save(PNG, optimize=True)
    data = PNG.read_bytes()
    lines = ['/* Generated by port/tools/gen_ra_emblem.py from port/assets/achievements/ra_emblem.png. */']
    for i in range(0, len(data), 24):
        lines.append(','.join(str(b) for b in data[i:i + 24]) + ',')
    INC.write_text('\n'.join(lines) + '\n', encoding='ascii', newline='\n')
    print(PNG, len(data), 'bytes')


if __name__ == '__main__':
    main()
