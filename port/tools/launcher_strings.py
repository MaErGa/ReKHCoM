"""The launcher's T("es", "en") pairs, as port/decompui/i18n/strings.json: one entry per English text, for the
translations to French, German, Italian and Japanese (port/decompui/i18n/<lang>.json, keyed by the English text).

    python port/tools/launcher_strings.py            # writes strings.json, lists what each language still lacks
    python port/tools/launcher_strings.py --emit     # also port/decompui/i18n_table.inc, the table built in
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / 'port' / 'decompui'
OUT = SRC / 'i18n'
LANGS = ('fr', 'de', 'it', 'ja')


def literal(s, i):
    """C string literals from s[i] on (adjacent ones joined), decoded as UTF-8; returns (text, end)."""
    out = bytearray()
    n = 0
    while True:
        while i < len(s) and s[i] in ' \t\r\n':
            i += 1
        if s.startswith('//', i):
            i = s.index('\n', i)
            continue
        if i >= len(s) or s[i] != '"':
            break
        i += 1
        n += 1
        while s[i] != '"':
            c = s[i]
            if c == '\\':
                e = s[i + 1]
                if e == 'x':
                    m = re.match(r'[0-9A-Fa-f]{1,2}', s[i + 2:])
                    out.append(int(m.group(0), 16))
                    i += 2 + len(m.group(0))
                    continue
                out += {'n': b'\n', 't': b'\t', '"': b'"', '\\': b'\\', "'": b"'"}[e]
                i += 2
                continue
            out += c.encode('utf-8')
            i += 1
        i += 1
    return (out.decode('utf-8') if n else None), i


def pairs():
    found = {}
    for path in sorted(list(SRC.glob('*.cpp')) + list(SRC.glob('*.inc'))):
        s = path.read_text(encoding='utf-8')
        for m in re.finditer(r'(?<![A-Za-z0-9_])T\(', s):
            es, i = literal(s, m.end())
            if es is None:
                continue
            while s[i] in ' \t\r\n':
                i += 1
            if s[i] != ',':
                continue
            en, i = literal(s, i + 1)
            if en is not None:
                found.setdefault(en, es)
    return found


def c_literal(text):
    return '"' + text.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n').replace('\t', '\\t') + '"'


def emit(rows):
    """port/decompui/i18n_table.inc: {en, fr, de, it, ja} per text (nullptr where a language lacks it: English)."""
    tables = {}
    for lang in LANGS:
        path = OUT / (lang + '.json')
        tables[lang] = json.loads(path.read_text(encoding='utf-8')) if path.exists() else {}
    lines = ['/* Generated by port/tools/launcher_strings.py --emit from the JSON files in port/decompui/i18n: do not edit. */',
             'static const char* const kI18n[][5] = {']
    for r in rows:
        cells = [c_literal(r['en'])]
        for lang in LANGS:
            t = tables[lang].get(r['en'])
            cells.append(c_literal(t) if t else 'nullptr')
        lines.append('    { ' + ', '.join(cells) + ' },')
    lines.append('};')
    (SRC / 'i18n_table.inc').write_text('\n'.join(lines) + '\n', encoding='utf-8')


def main():
    found = pairs()
    OUT.mkdir(exist_ok=True)
    rows = [{'en': en, 'es': es} for en, es in sorted(found.items())]
    (OUT / 'strings.json').write_text(json.dumps(rows, ensure_ascii=False, indent=1) + '\n', encoding='utf-8')
    print(len(rows), 'texts')
    for lang in LANGS:
        path = OUT / (lang + '.json')
        done = json.loads(path.read_text(encoding='utf-8')) if path.exists() else {}
        print(lang, 'missing', sum(1 for r in rows if r['en'] not in done))
    if '--emit' in sys.argv:
        emit(rows)
    return 0


if __name__ == '__main__':
    sys.exit(main())
