"""Scene 053's plateau beyond the map (Preliminar V1, user 24/10: "every tuft misses its half"): repeating a band of
columns always cuts some grass tufts in two. Here the plateau outside the map is laid out whole: the map's own plain
grass repeated (a tuft-free 4x4 block) and the map's own tufts, each placed entire, at the map's density, never
touching each other or the cliff. Written as a tile table: port/include/port/port_scene053_plateau.inc.

    python port/tools/gen_scene053_plateau.py
"""
import re
from pathlib import Path
import scene_tile_data as s

ROOT = Path(__file__).resolve().parents[2]
X0, X1, Y0, Y1 = -64, 128, -40, 64  # the table's tiles (map columns 0..63 inside are the map's own)
TUFT = (4, 5, 7)  # the tufts; the plain grass is 8, 9 and the light specks 10


def main():
    s.ROM = (ROOT / 'roms/B8CP.gba').read_bytes()
    syms = (ROOT / 'build/eu/pc/rom_symbols.s').read_text()
    b = s.load_bg(int(re.search(r'\.set _gEventBg053, (0x[0-9a-fA-F]+)', syms)[1], 16))
    g, td = b['bg3'], b['tiles']

    def tuft(x, y):
        e = g[y][x]
        return any(((td[(e & 1023) * 32 + yy * 4 + xx // 2] >> (xx % 2 * 4)) & 15) in TUFT
                   for yy in range(8) for xx in range(8))

    def high(x, y, margin=1):  # on the plateau, clear of the cliff's edge
        return 2 * y - x < -margin

    T = {(x, y): tuft(x, y) for y in range(64) for x in range(64)}

    def pixel(px, py):  # the colour index of a map pixel
        e = g[py // 8][px // 8]
        xx, yy = px % 8, py % 8
        fx = 7 - xx if e & 1024 else xx
        fy = 7 - yy if e & 2048 else yy
        return (td[(e & 1023) * 32 + fy * 4 + fx // 2] >> (fx % 2 * 4)) & 15

    # the plain grass: a tuft-free 4x4 block on the plateau, repeated
    base = None
    for by in range(0, 32, 4):
        for bx in range(0, 61, 4):
            if all(high(bx + i, by + j, 2) and not T[bx + i, by + j] for i in range(4) for j in range(4)):
                base = (bx, by)
                break
        if base:
            break
    # the stamps: windows of tiles whose outer ring of pixels is plain grass, so every tuft inside is whole
    stamps, taken, cands = [], set(), []
    for w in range(4, 11):
        for h in range(3, 8):
            for y in range(0, 64 - h + 1):
                for x in range(0, 64 - w + 1):
                    cells = [(x + i, y + j) for j in range(h) for i in range(w)]
                    if any(not high(c[0], c[1], 2) for c in cells):
                        continue
                    ring = [(px, y * 8) for px in range(x * 8, (x + w) * 8)] + [(px, (y + h) * 8 - 1) for px in range(x * 8, (x + w) * 8)]
                    ring += [(x * 8, py) for py in range(y * 8, (y + h) * 8)] + [((x + w) * 8 - 1, py) for py in range(y * 8, (y + h) * 8)]
                    if sum(pixel(px, py) in TUFT for px, py in ring) > len(ring) // 25:  # loose specks may be cut, clumps not
                        continue
                    inner = sum(pixel(px, py) in TUFT for px in range(x * 8, (x + w) * 8) for py in range(y * 8, (y + h) * 8))
                    if inner > 150:  # a whole clump, not a few specks
                        cands.append((inner / (w * h), inner, cells))
    for _, _, cells in sorted(cands, key=lambda c: (-c[1], -c[0])):  # the fullest windows first, not overlapping
        if not any(c in taken for c in cells):
            stamps.append(cells)
            taken.update(cells)
    plateau = sum(1 for (x, y) in T if high(x, y))
    density = sum(len(st) for st in stamps) / plateau
    print('base', base, 'stamps', len(stamps), 'density %.2f' % density, sorted(len(st) for st in stamps)[-10:])

    # lay out: plain everywhere, then whole tufts on a jittered grid, each with a free tile around it
    table = {}
    for y in range(Y0, Y1):
        for x in range(X0, X1):
            if not 0 <= x < 64 or y < 0:
                table[x, y] = (base[0] + x % 4, base[1] + y % 4)
    used = {(x, y) for x in range(-1, 65) for y in range(0, 64)}  # the map itself
    k, step = 0, 6
    for gy in range(Y0, Y1, step):
        for gx in range(X0, X1, step):
            st = stamps[k % len(stamps)]
            k += 7  # walk the tufts in a scattered order
            mx, my = min(p[0] for p in st), min(p[1] for p in st)
            ox, oy = gx + (k * 5) % 3, gy + (k * 3) % 3
            cells = [(ox + px - mx, oy + py - my) for px, py in st]
            if not all((cx, cy) in table and high(cx, cy, 2) for cx, cy in cells):
                continue
            if any((cx + i, cy + j) in used for cx, cy in cells for i in (-1, 0, 1) for j in (-1, 0, 1)):
                continue
            for (cx, cy), (px, py) in zip(cells, st):
                table[cx, cy] = (px, py)
                used.add((cx, cy))
    out = ['/* Generated by port/tools/gen_scene053_plateau.py: scene 053\'s plateau beyond the map, as map tiles (column, row).',
           ' * Columns %d..%d, rows %d..%d; inside the map (columns 0..63, rows 0..63) the map is its own. */' % (X0, X1 - 1, Y0, Y1 - 1),
           '#define SCENE053_PLATEAU_X0 %d' % X0, '#define SCENE053_PLATEAU_W %d' % (X1 - X0),
           '#define SCENE053_PLATEAU_Y0 %d' % Y0, '#define SCENE053_PLATEAU_H %d' % (Y1 - Y0),
           'static const uint8_t kScene053Plateau[SCENE053_PLATEAU_H][SCENE053_PLATEAU_W][2] = {']
    for y in range(Y0, Y1):
        out.append('    {' + ','.join('{%d,%d}' % table.get((x, y), (0, 0)) for x in range(X0, X1)) + '},')
    out.append('};')
    path = ROOT / 'port/include/port/port_scene053_plateau.inc'
    path.write_text('\n'.join(out) + '\n')
    print(path)


if __name__ == '__main__':
    main()
